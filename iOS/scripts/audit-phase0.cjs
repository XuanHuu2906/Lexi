// Read-only source audit; writes only the generated inventory under iOS/docs.
// Run from the repository root: rtk proxy node iOS/scripts/audit-phase0.cjs
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '../..');
const backendRequire = createRequire(path.join(root, 'backend/package.json'));
const ts = backendRequire('typescript');
const output = path.join(root, 'iOS/docs/contracts/endpoint-inventory.md');
const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
  const full = path.join(dir, entry.name);
  return entry.isDirectory() ? walk(full) : [full];
});
const decorators = node => (ts.canHaveDecorators(node) ? ts.getDecorators(node) : []) ?? [];
const calls = node => decorators(node).map(d => d.expression).filter(ts.isCallExpression);
const named = (node, name) => calls(node).find(c => c.expression.getText() === name);
const stringArg = call => {
  if (!call?.arguments.length) return '';
  const arg = call.arguments[0];
  if (!ts.isStringLiteral(arg)) throw new Error(`Review nonliteral route: ${arg.getText()}`);
  return arg.text;
};
const relative = file => path.relative(root, file).replaceAll('\\', '/');
const link = (file, label) => `[${label}](../../../${relative(file)})`;
const methods = new Map([['Get', 'GET'], ['Post', 'POST'], ['Patch', 'PATCH'], ['Put', 'PUT'], ['Delete', 'DELETE']]);
const rows = [];
const controllers = walk(path.join(root, 'backend/src')).filter(f => f.endsWith('.controller.ts')).sort();
for (const file of controllers) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  for (const cls of source.statements.filter(ts.isClassDeclaration)) {
    const controller = named(cls, 'Controller');
    if (!controller) continue;
    const prefix = stringArg(controller);
    for (const member of cls.members.filter(ts.isMethodDeclaration)) {
      const route = calls(member).find(c => methods.has(c.expression.getText()));
      if (!route) continue;
      const method = methods.get(route.expression.getText());
      const url = '/' + [prefix, stringArg(route)].filter(Boolean).join('/');
      const publicRoute = Boolean(named(member, 'Public') || named(cls, 'Public'));
      const admin = Boolean(named(cls, 'Roles') || named(member, 'Roles'));
      const auth = publicRoute ? 'Public' : admin ? 'JWT + role ADMIN' : 'JWT (cookie first, Bearer fallback)';
      const csrf = publicRoute || method === 'GET' ? 'Skipped' : 'Cookie + header required, including Bearer';
      const status = named(member, 'HttpCode')?.arguments[0]?.getText() ?? (method === 'POST' ? '201' : '200');
      const inputs = member.parameters.flatMap(p => {
        const dec = calls(p).find(c => ['Body', 'Query', 'Param', 'UploadedFile'].includes(c.expression.getText()));
        return dec ? [`${dec.getText()}: ${p.type?.getText() ?? 'untyped'}`] : [];
      }).join('; ') || '—';
      const throttle = named(member, 'Throttle')?.getText() ?? (named(member, 'AiThrottle') ? '20/min/IP (AI)' : '60/min/IP (global)');
      const line = source.getLineAndCharacterOfPosition(member.getStart()).line + 1;
      const target = member.body?.statements.filter(ts.isReturnStatement).map(s => s.expression?.getText().replace(/\s+/g, ' ')).join('; ') || 'See method body';
      rows.push({ method, url, auth, csrf, status, inputs, throttle, file, line, target });
    }
  }
}
const esc = text => String(text).replaceAll('|', '\\|').replace(/\s+/g, ' ');
let content = '# Endpoint inventory — NestJS source audit\n\n';
content += 'Generated by `iOS/scripts/audit-phase0.cjs`. Source only: default HTTP statuses are inferred from Nest decorators, not observed over HTTP. No database, secrets, or AI calls. See [mobile-api.md](mobile-api.md) for semantics and proposed endpoints.\n\n';
content += `Scanned ${controllers.length} controllers; found ${rows.length} routes. Admin routes are inventory only, outside the learner MVP. All paths are backend paths without the Next.js /api prefix.\n\n`;
content += '| Method | Path | Auth | CSRF today | Success status | Inputs | Rate | Source / handler |\n|---|---|---|---|---|---|---|---|\n';
for (const row of rows) content += `| ${row.method} | \`${row.url}\` | ${row.auth} | ${row.csrf} | ${row.status} | ${esc(row.inputs)} | ${esc(row.throttle)} | ${link(row.file, `${relative(row.file)}:${row.line}`)} |\n`;
content += '\n## Frontend API modules\n\n';
for (const file of walk(path.join(root, 'frontend/src/lib/api')).filter(f => f.endsWith('.ts')).sort()) content += `- ${link(file, relative(file))}\n`;
content += '\n## Request DTO definitions\n\n';
for (const file of walk(path.join(root, 'backend/src')).filter(f => f.endsWith('.dto.ts')).sort()) content += `- ${link(file, relative(file))}\n`;
content += '\n## Service delegation\n\n';
for (const row of rows) content += `- \`${row.method} ${row.url}\`: \`${esc(row.target).replaceAll('`', '')}\`\n`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, content);
console.log(`Wrote ${relative(output)}: ${controllers.length} controllers, ${rows.length} routes.`);
